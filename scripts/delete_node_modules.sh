#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"

if [ ! -f "$REPO_ROOT/package.json" ]; then
  echo "Error: package.json not found in $REPO_ROOT" >&2
  exit 1
fi
if [ ! -d "$REPO_ROOT/packages" ]; then
  echo "Error: packages/ directory not found in $REPO_ROOT" >&2
  exit 1
fi
if [ ! -d "$REPO_ROOT/auth-server" ]; then
  echo "Error: auth-server/ directory not found in $REPO_ROOT" >&2
  exit 1
fi

dirs=(
  "$REPO_ROOT"
  "$REPO_ROOT/auth-server"
  "$REPO_ROOT"/packages/*
  "$REPO_ROOT"/tests/*
)

for dir in "${dirs[@]}"; do
  target="$dir/node_modules"
  if [ -d "$target" ]; then
    echo "Deleting $target"
    rm -rf "$target"
  else
    echo "Skipping $target (not found)"
  fi
done

echo "Done."
